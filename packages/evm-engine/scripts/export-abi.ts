/**
 * Write the engine and lens ABIs (from `forge build`) into packages/sdk as typed constants, so the SDK, the
 * indexer and the app decode every event and call with viem's types. Run after changing the contracts:
 *   forge build && npx tsx scripts/export-abi.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const abi = (name: string) => JSON.parse(readFileSync(join(here, '..', 'out', `${name}.sol`, `${name}.json`), 'utf8')).abi;
const out = join(here, '..', '..', 'sdk', 'src', 'evm', 'generated.ts');
writeFileSync(out, `// Generated by packages/evm-engine/scripts/export-abi.ts from \`forge build\`. Do not edit.
export const flowEngineAbi = ${JSON.stringify(abi('FlowEngine'), null, 1)} as const;

export const notesLensAbi = ${JSON.stringify(abi('NotesLens'), null, 1)} as const;

export const noteTokenAbi = ${JSON.stringify(abi('NoteToken'), null, 1)} as const;

export const mockErc20Abi = ${JSON.stringify(abi('MockERC20'), null, 1)} as const;

export const homeGatewayAbi = ${JSON.stringify(abi('HomeGateway'), null, 1)} as const;

export const remoteVaultAbi = ${JSON.stringify(abi('RemoteVault'), null, 1)} as const;

export const remoteReceiptAbi = ${JSON.stringify(abi('RemoteReceipt'), null, 1)} as const;
`);
console.log(`wrote ${out}`);
